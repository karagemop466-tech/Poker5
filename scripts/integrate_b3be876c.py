def gtd_number(x):
    """Numeric guarantee in dollars, or None when not a money guarantee (e.g. '2 Seats')."""
    if x in (None, ""):
        return None
    s = str(x).split(";")[0]
    if re.search(r"[a-zA-Z]", s) and "$" not in s:
        return None
    s = re.sub(r"[^0-9.]", "", s)
    try:
        return float(s) if s else None
    except ValueError:
        return None


def reconcile_gtd(row: dict, verified_row: dict | None) -> str:
    """Return a warning if the two official captures disagree on the guarantee."""
    if not verified_row:
        return ""
    a = row.get("guarantee")
    b = verified_row.get("gtd")
    def num(x):
        return gtd_number(x)
    na, nb = num(a), num(b)
    if na is None and nb is None:
        return ""
    if na is None or nb is None or abs(na - nb) > 0.5:
        return "guarantee differs between the schedule-row capture (%s) and the structure-sheet capture (%s)" % (
            a if a not in (None, "") else "not stated",
            b if b not in (None, "") else "not stated")
    return ""


