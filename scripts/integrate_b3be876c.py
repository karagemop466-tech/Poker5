_MISSING = object()


def load(dirpath, name, default=_MISSING):
    p = os.path.join(dirpath, name)
    if not os.path.exists(p):
        if default is _MISSING:
            raise SystemExit("integrate: missing required input %s" % p)
        return default
    with open(p) as fh:
        return json.load(fh)


def rules_area(text: str) -> str:
    """Only the numbered-rule list of a sheet.

    A structure sheet is title, blind table, tail labels, then "1. TDA rules ...".
    Matching over the whole page would let the blind table and the title count as
    rule text, so everything before the first numbered rule is dropped.
    """
    if not text:
        return ""
    t = re.sub(r"\s+", " ", text)
    m = re.search(r"(?:^|\s)1\.\s*(?:TDA rules|The TDA|Rules)", t)
    if not m:
        m = re.search(r"(?:^|\s)1\.\s", t)
    return t[m.start():].strip() if m else t


def clip(s: str, n: int = 240) -> str:
    s = (s or "").strip()
    return s if len(s) <= n else s[:n - 1].rstrip() + "\u2026"


def sentences(text: str) -> list[str]:
    """Numbered-rule sentences of a structure sheet, whitespace normalised."""
    t = rules_area(text)
    if not t:
        return []
    return [s.strip() for s in re.split(r"(?<=[.;])\s+", t) if s.strip()]


def entry_language(rules_text: str) -> list[str]:
    return [clip(s) for s in sentences(rules_text) if ENTRY_GRANT.search(s)]


def flight_language(rules_text: str) -> list[str]:
    # only rule sentences that speak of bagging chips or another flight count;
    # the blind table's "Day 2" note is handled by the sheet's own parsed fields
    return [clip(s) for s in sentences(rules_text)
            if re.search(r"bags? chips|subsequent flight|starting flight|day\s*2", s, re.I)]


def rule_count(rules_text: str) -> int:
    """How many numbered rules the sheet lists (1., 2., ... )."""
    nums = {int(n) for n in re.findall(r"(?:^|\s)(\d{1,2})\.\s", rules_area(rules_text))}
    return max(nums) if nums else 0


def effective_date(rules_text: str) -> str:
    m = re.search(r"Effective\s+Date\s+(\d{2}\.\d{2}\.\d{2})", rules_text or "")
    return m.group(1) if m else ""


# ----------------------------------------------------------------- the one published standard
def time_norm(v) -> str:
    """'11:10 AM', '11:10', '11.10' -> '11:10' for comparison, '' when there is nothing to compare."""
    if v in (None, ""):
        return ""
    t = str(v).strip().lower().replace(".", ":").replace(" ", "")
    m = re.match(r"(\d{1,2}):(\d{2})", t)
    if not m:
        return t
    h, mi = int(m.group(1)), int(m.group(2))
    if mi > 59:
        return "%d:%02d" % (h, mi)
    if "pm" in t and h != 12:
        h += 12
    elif "am" in t and h == 12:
        h = 0
    elif h > 12:
        pass  # already 24-hour
    return "%d:%02d" % (h % 24, mi)


# "Guarantee: $30,000" is a money pool; "Guarantee: 2 Seats" is not - and a satellite's seat count
# must never be read as two dollars, which is what a bare number pattern did the first time.
GUAR_MONEY = re.compile(r"guarantee\s*:?\s*(\$\s*[0-9][0-9,]{2,}|[0-9][0-9,]{4,})", re.I)
GUAR_SEATS = re.compile(r"guarantee\s*:?\s*[0-9][0-9,.]*\s*(seat|ticket|entry|package)", re.I)


def sheet_guarantee_for(sheet: dict | None, event_no) -> tuple[float | None, str]:
    """The guarantee a structure sheet states FOR THIS EVENT, or None when it does not name one.

    A sheet can carry several guarantee lines - "Guarantee: $30,000 for Event #14 and #63" and
    "Guarantee: $40,000 for Event #28" sit on the same PDF - so reading the first number on the page
    turns a shared sheet into a fake disagreement. That is exactly how three events were wrongly
    reported as contradicted by their own sheet before this function existed.
    """
    text = ((sheet or {}).get("rules_text") or "")
    if not text.strip():
        return None, "no sheet text on file"
    lines = [ln.strip() for ln in re.split(r"(?:\\n|\n)+", text) if re.search(r"guarantee", ln, re.I)]
    if not lines:
        return None, "the structure sheet states no guarantee"
    try:
        want = int(str(event_no).strip())
    except (TypeError, ValueError):
        want = None
    if want is not None:
        for ln in lines:
            mentioned = {int(n) for n in re.findall(r"#\s*(\d{1,3})", ln)}
            m = GUAR_MONEY.search(ln)
            if m and want in mentioned:
                return float(re.sub(r"[^0-9.]", "", m.group(1))), ln[:200]
        if any(re.search(r"#\s*\d", ln) for ln in lines):
            return None, ("the sheet lists a guarantee per event number and does not name Event #%s, so it neither "
                          "confirms nor contradicts the figure on the schedule page" % event_no)
    if len(lines) == 1:
        m = GUAR_MONEY.search(lines[0])
        if m:
            return float(re.sub(r"[^0-9.]", "", m.group(1))), lines[0][:200]
    return None, ("the sheet lists %d guarantee lines without tying one to this event number, so no comparison is "
                  "possible" % len(lines))


def spot_check_row(row: dict, sheet: dict | None, read_date: str) -> dict:
    """Compare the published values of a row with the official document beside it, field by field.

    This is not a re-fetch - the monitor does that. It is the consistency check between the two
    official captures already stored in the repo: the schedule page line and the structure sheet.
    A disagreement is published, never silently resolved, because the two documents are both
    official and only the room can say which one is current.
    """
    fields = {}
    page_start, sheet_start = time_norm(row.get("start")), time_norm(row.get("sheet_start"))
    raw_sheet = str(row.get("sheet_start") or "")
    # A sheet that covers several flights or several events states one start time; the schedule page
    # states the one for this row. That is not a contradiction, and it must not be published as one.
    explained = None
    if row.get("kind") not in (None, "", "entry"):
        explained = ("this row is a %s, not a first-day entry: the sheet states the start of the day the "
                     "structure belongs to" % row.get("kind"))
    elif re.search(r"day\s*\d|1[AB]\b|flight", str(row.get("name") or ""), re.I):
        explained = "the event runs over more than one day or flight, so the sheet states a different day's start"
    elif re.search(r"day\s*1|/\s*#\d|\d:\d\d\s*[AP]M\s*/", raw_sheet, re.I):
        explained = ("the sheet lists the starts of several events or flights (%s), so it does not contradict "
                     "the time on this row" % raw_sheet[:80])
    if page_start and sheet_start:
        ok = page_start == sheet_start
        fields["start"] = {"published": row.get("start"), "ok": ok or bool(explained),
                           "excerpt": ("schedule page: \"%s\"  ||  structure sheet: \"%s\""
                                       % (row.get("start"), row.get("sheet_start")))
                           + ("" if ok or not explained else "  ||  " + explained),
                           "retrieved": read_date,
                           "note": ("the two official documents state different start times for this row - ask "
                                    "the room which one is current before planning around it" if not ok else
                                    (explained or "the schedule page and the structure sheet agree"))}
    elif sheet_start:
        fields["start"] = {"published": row.get("start"), "ok": False,
                           "excerpt": "the schedule page states no start time for this row, so the sheet is "
                                      "the only figure on file",
                           "retrieved": read_date}
    g_page = gtd_number(row.get("guarantee"))
    g_sheet, g_src = sheet_guarantee_for(sheet, row.get("event_no"))
    seat_row = bool(re.search(r"[a-zA-Z]", str(row.get("guarantee") or ""))) and "$" not in str(row.get("guarantee") or "")
    if seat_row:
        # A satellite guarantees seats. There is no cash pool to compare and none to divide a buy-in by,
        # so the row is labelled and left out of the ranking instead of being scored against a money figure.
        fields["guarantee"] = {"published": row.get("guarantee"), "ok": True,
                               "excerpt": ("satellite: the published guarantee is %s, not a cash pool%s"
                                           % (row.get("guarantee"), ("; the sheet says: " + g_src) if g_src else "")),
                               "retrieved": read_date,
                               "note": "seat guarantee - counted separately, never ranked on guarantee divided by entry fee"}
        row.pop("guarantee_note", None)
    if g_page is not None and g_sheet is not None and not seat_row:
        fields["guarantee"] = {"published": g_page, "ok": g_page == g_sheet,
                               "excerpt": ("structure sheet, this event: %s" % g_src) if g_page == g_sheet else
                                          ("schedule page: \"%s\"  ||  structure sheet: \"%s\""
                                           % (row.get("guarantee"), g_src)),
                               "retrieved": read_date}
    elif (row.get("guarantee") or g_sheet is not None) and not seat_row:
        seat = bool(re.search(r"[a-zA-Z]", str(row.get("guarantee") or ""))) and "$" not in str(row.get("guarantee"))
        blank_sheet = g_sheet is None
        note = ""
        if seat and blank_sheet:
            note = ("this row guarantees %s, not a cash pool - there is no money figure on the sheet to compare, "
                    "and a seat guarantee is never divided by a buy-in" % row.get("guarantee"))
        elif blank_sheet:
            note = "the structure sheet states no guarantee, so the schedule page is the only figure on file"
        fields["guarantee"] = {"published": row.get("guarantee"),
                               "ok": bool(note) or (str(row.get("guarantee") or "").strip()
                                                    == str((sheet or {}).get("guarantee") or "").strip()),
                               "excerpt": "at least one of the two captures states no money guarantee"
                                          + (("  ||  " + note) if note else ""),
                               "retrieved": read_date, "note": note}
    buy = row.get("buyin")
    if buy and sheet and sheet.get("buyin") not in (None, ""):
        fields["buyin"] = {"published": float(buy), "ok": float(buy) == float(sheet["buyin"]),
                           "excerpt": "schedule page: $%s  ||  structure sheet: $%s" % (buy, sheet["buyin"]),
                           "retrieved": read_date}
    elif buy:
        # the sheet does not repeat the buy-in in a field of its own: check the number appears in it
        text = (sheet or {}).get("rules_text") or ""
        hit = ("$%s" % format(int(buy), ",d")) in text or str(int(buy)) in text
        fields["buyin"] = {"published": float(buy), "ok": bool(hit),
                           "excerpt": ("the buy-in number appears in the structure sheet's own text" if hit else
                                       "the number published from the schedule page does not appear in the "
                                       "structure sheet - re-read both before you rely on it"),
                           "retrieved": read_date}
    if row.get("rule_excerpt"):
        fields["entry_rule"] = {"published": {"confirmed_single": "confirmed single-entry",
                                              "multi": "multi-entry", "unknown": "cap not stated",
                                              "unread": "terms not read"}.get(row.get("entry_rule"), ""),
                                "ok": True, "excerpt": row["rule_excerpt"][:300],
                                "retrieved": read_date}
    out = {"fields": fields, "checked_on": read_date, "checked_by": "scripts/integrate_b3be876c.py",
           "basis": "the two official captures stored in data/c6087e2c/ compared field by field"}
    out["mismatches"] = sum(1 for v in fields.values() if not v["ok"])
    return out


def derive_verdict(row: dict, sheet: dict | None, kind: str) -> tuple[str, str, dict]:
    """Return (entry_rule, basis, evidence) for one Venetian schedule row.

    confirmed_single  the row's own official structure sheet was read in full, it
                      names this event number, the event is one day with a stated
                      registration close, and nothing in its rule list grants a
                      further entry, buy-back, add-on or purchased stack.
    multi             an official source grants further entries / flights, or the
                      row is a Day-2 restart or final table.
    unknown           the sheet was read but does not let the test be run (no
                      registration close, or the event is not named on it).
    unread            no official sheet was read for this row.
    """
    ev = {"sheet_no": None, "sheet_sha256": "", "sheet_retrieved": "", "rules_read": 0,
          "effective_date": "", "grant_sentences": [], "flight_sentences": [],
          "registration_close": "", "covers_event": False, "one_day": None}
    if sheet is None:
        return "unread", "no official structure sheet was read for this row", ev
    ev["sheet_no"] = sheet.get("sheet_no")
    ev["sheet_sha256"] = sheet.get("pdf_sha256") or ""
    ev["sheet_retrieved"] = sheet.get("retrieved_at") or ""
    rt = sheet.get("rules_text") or ""
    ev["rules_read"] = rule_count(rt)
    ev["effective_date"] = effective_date(rt)
    ev["grant_sentences"] = entry_language(rt)
    ev["flight_sentences"] = flight_language(rt)
    ev["registration_close"] = sheet.get("late_registration") or ""
    nums = sheet.get("event_numbers") or []
    try:
        en = int(str(row.get("event_no")))
    except (TypeError, ValueError):
        en = None
    ev["covers_event"] = en in nums if en is not None else False

    if ev["grant_sentences"]:
        return ("multi",
                "official sheet %s rule text grants further entries: %s"
                % (ev["sheet_no"], ev["grant_sentences"][0][:180]), ev)
    if kind in ("restart", "final_table") or ev["flight_sentences"]:
        why = "the row is a Day 2 / final-table continuation" if kind != "entry" else \
              "flight language on the sheet: " + ev["flight_sentences"][0][:150]
        return "multi", why, ev
    if sheet.get("multi_day_format"):
        return "multi", "the sheet describes a multi-day format", ev
    if sheet.get("http_status") != 200:
        return "unread", "the official sheet could not be retrieved", ev
    if not ev["covers_event"]:
        return ("unknown",
                "the sheet linked from this row does not name event #%s, so its rule "
                "list cannot be attributed to this event (flag F33)" % row.get("event_no"), ev)
    if not ev["registration_close"]:
        return ("unknown",
                "the sheet states no registration close, so a single entry cannot be "
                "confirmed from it", ev)
    return ("confirmed_single",
            "sheet %s read %s (sha256 %s...): %d numbered rules, no re-entry, rebuy, "
            "add-on or purchased-stack provision; one-day format; registration closes "
            "%s" % (ev["sheet_no"], (ev["sheet_retrieved"] or "")[:10],
                    (ev["sheet_sha256"] or "")[:12], ev["rules_read"], ev["registration_close"]),
            ev)


